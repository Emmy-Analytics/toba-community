import puppeteer from 'puppeteer';
import { createServer } from 'http';
import { readFileSync, existsSync } from 'fs';
import { join, extname } from 'path';
const root = process.cwd();
const mime = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg' };
const server = createServer((req, res) => { let p = req.url.split('?')[0]; if (p === '/') p = '/index.html'; const f = join(root, decodeURIComponent(p)); if (!existsSync(f)) { res.writeHead(404); res.end(); return; } res.writeHead(200, { 'Content-Type': mime[extname(f)] || 'application/octet-stream' }); res.end(readFileSync(f)); });
await new Promise(r => server.listen(8943, r));
const b = await puppeteer.launch({ headless: 'new' });
const page = await b.newPage();
const errs = []; page.on('pageerror', e => errs.push(e.message));
await page.setViewport({ width: 390, height: 844 });
await page.goto('http://127.0.0.1:8943/index.html', { waitUntil: 'domcontentloaded' });
await new Promise(r => setTimeout(r, 3500));
const res = {};
res.before = await page.evaluate(() => document.querySelector('.cut-stage .tier-main')?.src.slice(-18));
/* puppeteer touchscreen dispatches real touch->pointer events */
await page.touchscreen.touchStart(195, 480);
await page.touchscreen.touchMove(60, 480);
await page.touchscreen.touchMove(20, 480);
await page.touchscreen.touchEnd();
await new Promise(r => setTimeout(r, 900));
res.after = await page.evaluate(() => document.querySelector('.cut-stage .tier-main')?.src.slice(-18));
res.changed = res.before !== res.after;
/* swipe back other direction */
await page.touchscreen.touchStart(60, 480);
await page.touchscreen.touchMove(300, 480);
await page.touchscreen.touchEnd();
await new Promise(r => setTimeout(r, 900));
res.back = await page.evaluate(() => document.querySelector('.cut-stage .tier-main')?.src.slice(-18));
res.backChanged = res.back !== res.after;
console.log(JSON.stringify(res, null, 1), 'ERRS:', JSON.stringify(errs));
await b.close(); server.close();
